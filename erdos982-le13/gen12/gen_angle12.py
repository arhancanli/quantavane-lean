# Generate E982C/Angle12.lean: the n = 12 angle certificate (core1.cert) as a Lean proof, generic over a relabelling g.
import json
from fractions import Fraction as F
import os
HERE=os.path.dirname(os.path.abspath(__file__))
E12=HERE+'/'
OUT=HERE+'/../E982C/Angle12.lean'
d=json.load(open(E12+'core1.cert'))
n=12
def between(v,x,y,z):
    px,py,pz=((x-v)%n,(y-v)%n,(z-v)%n)
    return min(px,pz)<py<max(px,pz) and 0 not in (px,py,pz)
def nm(v,a,b): return (v,min(a,b),max(a,b))
def T(v,a,b): return f'th p (g {v}) (g {a}) (g {b})'
def lin_str(dct, pi):
    terms=[]
    for k,c in sorted(dct.items()):
        if c==0: continue
        terms.append((c, T(*k)))
    if pi!=0: terms.append((pi,'Real.pi'))
    s=''
    for i,(c,t) in enumerate(terms):
        cs = f'({c.numerator}/{c.denominator})' if c.denominator!=1 else f'{abs(c.numerator) if i>0 else c.numerator}'
        if c.denominator!=1:
            cc = abs(c) if i>0 else c
            cs = f'({cc.numerator}/{cc.denominator})' if cc.denominator!=1 else f'{cc.numerator}'
        sign = '' if i==0 else (' + ' if c>0 else ' - ')
        s += f'{sign}{cs} * {t}'
    return s
core=[tuple(r[1:]) for r in d['core']]
Arows=[]; facts=[]; lines=[]; total={}; pitot=F(0)
def addvec(vec, coef):
    global pitot
    for k,c in vec.items():
        if k=='pi': pitot+=coef*c
        else: total[k]=total.get(k,0)+coef*c
for idx,(lab,yv) in enumerate(d['y']):
    y=F(yv); k=lab[0]; name=f'{k}{idx}'
    if k=='T':
        a,b,c=sorted(lab[1:])
        lines.append(f'  have {name} := T_th (p := p) hinj (a := g {a}) (b := g {b}) (g {c}) (hg.ne (by decide))')
        # Lean fact: th a b c + th b a c + th c a b - pi
        vec={nm(a,b,c):1, nm(b,a,c):1, nm(c,a,b):1, 'pi':-1}
        row={nm(a,b,c):1, nm(b,a,c):1, nm(c,a,b):1, 'pi':-1}
    elif k=='A':
        v,x,yy,z=lab[1:]; assert between(v,x,yy,z), lab
        Arows.append((v,x,yy,z))
        lines.append(f'  have {name} := A_th (p := p) hp (v := g {v}) (x := g {x}) (y := g {yy}) (z := g {z}) (hA ({v}, {x}, {yy}, {z}) (by decide))')
        rws=[f'th_comm (p := p) (g {v}) (g {a}) (g {b})' for (a,b) in ((x,z),(x,yy),(yy,z)) if a>b]
        if rws: lines.append(f'  rw [{", ".join(rws)}] at {name}')
        vec={nm(v,x,z):1, nm(v,x,yy):-1, nm(v,yy,z):-1}
        row=vec
    else:
        o,pp,q=lab[1:]
        assert (o,pp,q) in core or (o,q,pp) in core
        e=(o,pp,q) if (o,pp,q) in core else (o,q,pp)
        a,b=e[1],e[2]
        lines.append(f'  have {name} := E_th (p := p) (o := g {o}) (a := g {a}) (b := g {b}) (hE ({o}, {a}, {b}) (by decide))')
        # Lean fact: th a o b = th b o a
        rws=[]
        if o>b: rws.append(f'th_comm (p := p) (g {a}) (g {o}) (g {b})')
        if o>a: rws.append(f'th_comm (p := p) (g {b}) (g {o}) (g {a})')
        if rws: lines.append(f'  rw [{", ".join(rws)}] at {name}')
        vec={nm(a,o,b):1, nm(b,o,a):-1}
        # certificate row for ('E',o,p,q): th(q;o,p) - th(p;o,q)
        row={nm(q,o,pp):1, nm(pp,o,q):-1}
    # sign of Lean fact relative to the certificate row
    if vec==row: s=1
    elif {k2:-c for k2,c in vec.items()}==row: s=-1
    else: raise Exception(('mismatch',lab,vec,row))
    facts.append((name, y*s, vec))
    addvec(vec, y*s)
nz={k:c for k,c in total.items() if c!=0}
assert pitot==F(-5,4), pitot
key_lhs=lin_str(nz,0)
lc=' + '.join(f'({c.numerator}/{c.denominator}) * {nmf}' if c.denominator!=1 else f'({c.numerator}) * {nmf}' for nmf,c,_ in facts)
bounds=[]
for k,c in sorted(nz.items()):
    if c>0: bounds.append(f'th_le_pi (p := p) (g {k[0]}) (g {k[1]}) (g {k[2]})')
    else: bounds.append(f'th_nonneg (p := p) (g {k[0]}) (g {k[1]}) (g {k[2]})')
coreE_s=', '.join(f'({o}, {a}, {b})' for o,a,b in core)
coreA_s=',\n  '.join(', '.join(f'({v}, {x}, {y}, {z})' for v,x,y,z in Arows[i:i+6]) for i in range(0,len(Arows),6))
nT=sum(1 for f in facts if f[0][0]=='T'); nA=len(Arows); nE=sum(1 for f in facts if f[0][0]=='E')
